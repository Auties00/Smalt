#!/usr/bin/env python3
"""Writes each Smalt artifact's META-INF/THIRD-PARTY-NOTICES from the combined notices.

build-notices.sh assembles THIRD-PARTY-NOTICES (next to this script) with one numbered section per
upstream project, each naming the Smalt packages derived from it under "Derived Smalt packages:".
This script gives every code artifact the sections whose packages it contains, plus the sections those
sections refer to ("see section 17"), and renders them under an artifact-specific header.

The package -> artifact map comes from the source tree (every directory under an artifact's
src/main/java/com/github/auties00/smalt that holds a .java file) and is written to packages.tsv for
reference. A token of a "Derived Smalt packages:" list that looks like a Smalt package (its first segment is
a top-level Smalt package) but names no package of the tree fails the run, so a renamed or moved package
cannot silently drop its notices; file names such as kiss_fft.c or vorbis-setup.bin.gz are not packages.

Usage: split-notices.py [smalt root]   (default: the repository this script lives in)
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else os.path.dirname(os.path.dirname(HERE))
GROUP = 'com.github.auties00'
BASE = 'com.github.auties00.smalt'
CODE = ['core', 'image', 'audio', 'video', 'mpeg', 'capture', 'raw', 'desktop', 'aot']
TITLE = {'core': 'Core', 'image': 'Image', 'audio': 'Audio', 'video': 'Video', 'mpeg': 'MPEG',
         'capture': 'Capture', 'raw': 'Raw', 'desktop': 'Desktop', 'aot': 'AOT'}
MODULE = {a: BASE if a == 'core' else BASE + '.' + a for a in CODE}
RULE = '=' * 79
SOURCES = os.path.join('src', 'main', 'java', *BASE.split('.'))
EXTENSIONS = {'asm', 'bin', 'c', 'cc', 'cpp', 'gz', 'h', 'hpp', 'inc', 'java', 'js', 'md', 'py', 's', 'sh', 'txt',
              'wasm'}


def fill(words, width):
    lines, current = [], ''
    for word in words:
        if current and len(current) + 1 + len(word) > width:
            lines.append(current)
            current = word
        else:
            current = (current + ' ' + word) if current else word
    if current:
        lines.append(current)
    return lines


def packages():
    """Maps every package of the source tree, relative to BASE, to the artifact that holds it."""
    known = {}
    for artifact in CODE:
        top = os.path.join(ROOT, artifact, SOURCES)
        for directory, _, files in os.walk(top):
            if any(name.endswith('.java') for name in files):
                package = os.path.relpath(directory, top).replace(os.sep, '.')
                package = '' if package == '.' else package
                if package in known and known[package] != artifact:
                    sys.exit(f'package {package or BASE} is in both {known[package]} and {artifact}')
                known[package] = artifact
    with open(os.path.join(HERE, 'packages.tsv'), 'w', encoding='utf-8', newline='\n') as sink:
        sink.write('# Package (relative to com.github.auties00.smalt) -> artifact. Generated by split-notices.py from '
                   'the source tree; do not edit.\n')
        for package in sorted(known):
            sink.write(f'{package}\t{known[package]}\n')
    return known


def derived(number, text, known):
    """Returns the artifacts of the packages a section's "Derived Smalt packages:" list names."""
    tops = {package.split('.')[0] for package in known if package}
    found = set()
    for token in re.findall(r'[a-z][a-z0-9]*(?:\.[a-z0-9]+)+', text):
        if token in known:
            found.add(known[token])
        elif token.split('.')[-1] not in EXTENSIONS and token.split('.')[0] in tops:
            sys.exit(f'notice section {number} names {token}, which is not a package of the source tree')
    return found


def sections(lines):
    starts = [i for i in range(len(lines) - 2)
              if lines[i] == RULE and re.match(r'^\d+\. ', lines[i + 1]) and lines[i + 2] == RULE]
    if not starts:
        sys.exit('THIRD-PARTY-NOTICES has no numbered sections')
    result = []
    for k, start in enumerate(starts):
        end = starts[k + 1] if k + 1 < len(starts) else len(lines)
        result.append((int(re.match(r'^(\d+)\.', lines[start + 1]).group(1)), lines[start:end]))
    return lines[:starts[0]], result


def render(artifact, header, chosen):
    numbers = {n for n, _ in chosen}
    kept = []
    for paragraph in '\n'.join(header[2:]).strip('\n').split('\n\n'):
        if paragraph.startswith('Smalt (https://'):
            paragraph = '\n'.join(fill((f'Smalt {TITLE[artifact]} (Maven artifact {GROUP}:smalt-{artifact}, JPMS '
                                        f'module {MODULE[artifact]}) is part of Smalt, a pure-Java media library '
                                        f'(https://github.com/Auties00/Smalt), and is licensed under the MIT '
                                        f'License.').split(), 79))
        elif paragraph.startswith('This software is based in part on the work of the Independent JPEG Group'):
            if not any('Independent JPEG Group' in '\n'.join(body[:3]) for _, body in chosen):
                continue
        elif paragraph.startswith('Contents'):
            rows = [paragraph.split('\n')[0]]
            for row in paragraph.split('\n')[1:]:
                m = re.match(r'^\s+(\d+)\.', row)
                if m and int(m.group(1)) in numbers:
                    rows.append(row)
            paragraph = '\n'.join(rows)
        elif 'covered by patents' in paragraph and artifact != 'mpeg':
            continue
        kept.append(paragraph)
    if not chosen:
        kept = [kept[0], 'This module contains no code derived from third-party projects.']
    title = f'Smalt {TITLE[artifact]}: Third-Party Notices'
    out = [title, '=' * len(title), ''] + '\n\n'.join(kept).split('\n') + ['', '']
    for _, body in chosen:
        out.extend(body)
    return '\n'.join(out).rstrip('\n') + '\n'


def main():
    with open(os.path.join(HERE, 'THIRD-PARTY-NOTICES'), encoding='utf-8') as source:
        header, numbered = sections(source.read().replace('\r\n', '\n').split('\n'))
    known = packages()
    owners, refs = {}, {}
    for number, body in numbered:
        joined = '\n'.join(body)
        m = re.search(r'Derived Smalt packages:\n(.*?)(?:\n\n|\Z)', joined, re.S)
        found = derived(number, m.group(1) if m else '', known)
        if not found:
            sys.exit(f'notice section {number} names no known package')
        owners[number] = found
        refs[number] = {int(x) for x in re.findall(r'\b(?:see|in) sections? (\d+)(?![\w(])', joined)}
    for artifact in CODE:
        chosen = {n for n, arts in owners.items() if artifact in arts}
        grown = True
        while grown:
            grown = False
            for n in list(chosen):
                for r in refs[n] - chosen:
                    if r in owners:
                        chosen.add(r)
                        grown = True
        target = os.path.join(ROOT, artifact, 'src', 'main', 'resources', 'META-INF', 'THIRD-PARTY-NOTICES')
        os.makedirs(os.path.dirname(target), exist_ok=True)
        with open(target, 'w', encoding='utf-8', newline='\n') as sink:
            sink.write(render(artifact, header, [(n, b) for n, b in numbered if n in chosen]))
        print('wrote', os.path.relpath(target, ROOT))


if __name__ == '__main__':
    main()
