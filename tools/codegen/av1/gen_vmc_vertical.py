"""Regenerates the floating-point vertical filter kernels of VectorMcDsp.java in place.

Usage: gen_vmc_vertical.py <VectorMcDsp.java>

The methods `vertical` and `verticalSix` (clamped result) and `verticalPlain` and `verticalPlainSix` (no clamp,
a subtracted bias) are four output rows by up to eleven source rows of straight-line code, too repetitive to
maintain by hand and within a few bytes of the module's 2000-byte kernel limit. The `Six` variants serve the
filters whose first and last taps are zero and read taps 1 to 6 only. Each source row is converted from 16-bit
integers to floats in one step (S2F): two steps (S2I, then I2F) leave the compiled graph so close to C2's inlining
budget that in some JVMs the last multiply-adds are not inlined and allocate on every call. This script rewrites the two pairs, javadoc
included, between their begin and end marker comments; everything outside the markers is hand-written. After a
change run `McDspTest` and `JitRobustnessTest`.
"""
import sys
import textwrap

R = 4
DOC_WIDTH = 97
EIGHT_TAPS = (0, 7)
SIX_TAPS = (1, 6)
BEGIN = '    // Begin generated by tools/codegen/av1/gen_vmc_vertical.py; edit the generator.\n'
END = '    // End generated by tools/codegen/av1/gen_vmc_vertical.py.\n'
TAP_NAMES = ('first', 'second', 'third', 'fourth', 'fifth', 'sixth', 'seventh', 'eighth')


def gen(name, base, clamp, taps, rows_per_step=R):
    lines = []
    a = lines.append
    first, last = taps
    sig_extra = ', int lo, int hi' if clamp else ', int sub'
    head = '    private static void %s(' % name
    pad = ' ' * len('    private static void %s(' % base)
    a(head + 'short[] src, int origin, int srcStride, short[] dst, int dstOff,')
    a(pad + 'int dstStride, int w, int rows, ' + ', '.join('int t%d' % k for k in range(first, 6)) + ',')
    a(pad + ''.join('int t%d, ' % k for k in range(6, last + 1)) + 'int rnd, int sh%s) {' % sig_extra)
    for k in range(first, last + 1):
        a('        var c%d = FloatVector.broadcast(F256, (float) t%d);' % (k, k))
    a('        var round = FloatVector.broadcast(F256, (float) rnd);')
    if clamp:
        a('        var low = IntVector.broadcast(I256, lo);')
        a('        var high = IntVector.broadcast(I256, hi);')
    else:
        a('        var minus = IntVector.broadcast(I256, sub);')
    a('        var row = origin;')
    a('        var out = dstOff;')
    a('        for (var y = 0; y < rows; y += %d, row += %d * srcStride, out += %d * dstStride) {'
      % (rows_per_step, rows_per_step, rows_per_step))
    for k in range(first, last + 1):
        a('            var k%d = FLOAT256.cast(c%d);' % (k, k))
    a('            var bias = FLOAT256.cast(round);')
    a('            for (var x = 0; x < w; x += 8) {')
    a('                var p = row + x;')
    started = [False] * rows_per_step
    for s in range(first, rows_per_step + last):
        a('                var m%d = FLOAT256.cast(SHORT128.cast(ShortVector.fromArray(S128, src, p + %s))'
          % (s, ('%d * srcStride' % s) if s else '0'))
        a('                        .convertShape(VectorOperators.S2F, F256, 0));')
        for o in range(rows_per_step):
            k = s - o
            if first <= k <= last:
                if not started[o]:
                    a('                var a%d = m%d.lanewise(VectorOperators.MUL, k%d).lanewise(VectorOperators.ADD, bias);'
                      % (o, s, k))
                    started[o] = True
                else:
                    a('                a%d = a%d.lanewise(VectorOperators.ADD, m%d.lanewise(VectorOperators.MUL, k%d));'
                      % (o, o, s, k))
    for o in range(rows_per_step):
        a('                var v%d = INT256.cast(a%d.convert(VectorOperators.F2I, 0)).lanewise(VectorOperators.ASHR, sh)'
          % (o, o))
        if clamp:
            a('                        .lanewise(VectorOperators.MAX, INT256.cast(low))')
            a('                        .lanewise(VectorOperators.MIN, INT256.cast(high));')
        else:
            a('                        .lanewise(VectorOperators.SUB, INT256.cast(minus));')
        a('                SHORT128.cast(v%d.convertShape(VectorOperators.I2S, S128, 0))' % o)
        a('                        .intoArray(dst, out + x + %s);' % (('%d * dstStride' % o) if o else '0'))
    a('            }')
    a('        }')
    a('    }')
    return '\n'.join(lines)


def doc(clamp, taps):
    filter_ = ', for a filter whose first and last taps are zero' if taps == SIX_TAPS else ''
    summary = ('Filters columns vertically, 8 outputs wide and %(r)d rows at a time, with the arithmetic in '
               'single-precision floats%(filter)s: the samples, the taps and every partial sum are integers below '
               '2^24 in magnitude, so each float operation is exact and the result is the same integer sum a 32-bit '
               'pass computes. Each source row is converted once for the up to %(r)d outputs it feeds, and a '
               'single-precision multiply and add each cost one instruction where a 32-bit multiply costs two.'
               % {'r': R, 'filter': filter_})
    lines = ['    /**']
    lines += textwrap.wrap(summary, width=DOC_WIDTH, initial_indent='     * ', subsequent_indent='     * ',
                           break_long_words=False, break_on_hyphens=False)
    lines.append('     *')
    lines.append('     * <p>The value of each output is {@code (sum + rnd) >> sh}%s.'
                 % (', clamped to the bounds' if clamp else ', minus {@code sub}'))
    lines.append('     *')
    params = [('src', 'the source'),
              ('origin', 'the index of the source sample under the first tap of the first output'),
              ('srcStride', 'the source row stride, which is also the distance between taps'),
              ('dst', 'the destination'),
              ('dstOff', 'the index of the first output'),
              ('dstStride', 'the destination row stride'),
              ('w', 'the number of outputs per row, a multiple of 8'),
              ('rows', 'the number of rows, a multiple of %d' % R)]
    params += [('t%d' % k, 'the %s tap' % TAP_NAMES[k]) for k in range(taps[0], taps[1] + 1)]
    params += [('rnd', 'the rounding constant'), ('sh', 'the shift')]
    if clamp:
        params += [('lo', 'the lower clamp'), ('hi', 'the upper clamp')]
    else:
        params += [('sub', 'the value subtracted after the shift')]
    for name, text in params:
        lines.append('     * @param %s %s' % (name, text))
    lines.append('     */')
    return '\n'.join(lines) + '\n'


def method(name, base, clamp, taps):
    return doc(clamp, taps) + gen(name, base, clamp, taps) + '\n'


def region(names, taps):
    clamped, plain = names
    return (BEGIN + method(clamped, 'vertical', True, taps) + '\n'
            + method(plain, 'verticalPlain', False, taps) + END)


def replace(text, block, occurrence):
    start = -1
    for _ in range(occurrence + 1):
        start = text.index(BEGIN, start + 1)
    end = text.index(END, start) + len(END)
    return text[:start] + block + text[end:]


def main(path):
    with open(path, newline='') as f:
        text = f.read()
    crlf = '\r\n' in text
    text = text.replace('\r\n', '\n')
    if text.count(BEGIN) != 2 or text.count(END) != 2:
        raise SystemExit('%s: expected two pairs of generator markers' % path)
    text = replace(text, region(('vertical', 'verticalPlain'), EIGHT_TAPS), 0)
    text = replace(text, region(('verticalSix', 'verticalPlainSix'), SIX_TAPS), 1)
    with open(path, 'w', newline='') as f:
        f.write(text.replace('\n', '\r\n') if crlf else text)


if __name__ == '__main__':
    main(sys.argv[1])
