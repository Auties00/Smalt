    /**
     * Returns the {@code dc_scaler} of Table 7-1.
     *
     * @param quantizer the quantizer scale, from 1 to 31
     * @param luma      whether the block is a luminance block
     * @return the scaler
     */
    public static int dcScaler(int quantizer, boolean luma) {
        if (quantizer < 5) {
            return 8;
        }
        if (luma) {
            return quantizer < 9 ? 2 * quantizer : quantizer < 25 ? quantizer + 8 : 2 * quantizer - 16;
        }
        return quantizer < 25 ? (quantizer + 13) / 2 : quantizer - 6;
    }

    /**
     * Builds a coefficient table from rows whose last, run and level start at a column.
     *
     * @param rows   the rows as colon-separated fields, the code first
     * @param column the index of the last field
     * @param escape the escape code
     * @return the table
     */
    private static Vlc coefficients(String[] rows, int column, String escape) {
        var codes = new String[rows.length * 2 + 1];
        var symbols = new int[rows.length * 2 + 1];
        for (var i = 0; i < rows.length; i++) {
            var fields = rows[i].split(":");
            var last = Integer.parseInt(fields[column]);
            var run = Integer.parseInt(fields[column + 1]);
            var level = Integer.parseInt(fields[column + 2]);
            var symbol = last << 15 | run << 9 | level;
            codes[2 * i] = fields[0] + "0";
            symbols[2 * i] = symbol;
            codes[2 * i + 1] = fields[0] + "1";
            symbols[2 * i + 1] = symbol | 1 << 8;
        }
        codes[rows.length * 2] = escape;
        symbols[rows.length * 2] = ESCAPE;
        return new Vlc(9, codes, symbols);
    }

    /**
     * Derives the largest level of every {@code last, run} pair of a coefficient table.
     *
     * @param rows the rows as {@code "code:last:run:level"}
     * @return the levels indexed {@code last * 64 + run}
     */
    private static int[] maxLevels(String[] rows) {
        var result = new int[128];
        for (var row : rows) {
            var fields = row.split(":");
            var index = Integer.parseInt(fields[1]) * 64 + Integer.parseInt(fields[2]);
            result[index] = Math.max(result[index], Integer.parseInt(fields[3]));
        }
        return result;
    }

    /**
     * Derives the largest run of every {@code last, level} pair of a coefficient table.
     *
     * @param rows the rows as {@code "code:last:run:level"}
     * @return the runs indexed {@code last * 64 + level}, {@code -1} where no code exists
     */
    private static int[] maxRuns(String[] rows) {
        var result = new int[128];
        Arrays.fill(result, -1);
        for (var row : rows) {
            var fields = row.split(":");
            var index = Integer.parseInt(fields[1]) * 64 + Integer.parseInt(fields[3]);
            result[index] = Math.max(result[index], Integer.parseInt(fields[2]));
        }
        return result;
    }

    /**
     * Builds the motion vector difference table of Table B-12, whose positive differences are
     * coded as the negative ones with the last bit inverted.
     *
     * @return the table
     */
    private static Vlc motionVectorDifferences() {
        String[] negative = {
                "0000 0000 0010 1", "0000 0000 0011 1", "0000 0000 0101", "0000 0000 0111",
                "0000 0000 1001", "0000 0000 1011", "0000 0000 1101", "0000 0000 1111",
                "0000 0001 001", "0000 0001 011", "0000 0001 101", "0000 0001 111",
                "0000 0010 001", "0000 0010 011", "0000 0010 101", "0000 0010 111",
                "0000 0011 001", "0000 0011 011", "0000 0011 101", "0000 0011 111",
                "0000 0100 001", "0000 0100 011", "0000 0100 11", "0000 0101 01",
                "0000 0101 11", "0000 0111", "0000 1001", "0000 1011",
                "0000 111", "0001 1", "0011", "011"
        };
        var codes = new String[65];
        var symbols = new int[65];
        for (var i = 0; i < 32; i++) {
            codes[i] = negative[i];
            symbols[i] = i;
            var bits = negative[i].replace(" ", "");
            codes[64 - i] = bits.substring(0, bits.length() - 1) + (bits.endsWith("1") ? "0" : "1");
            symbols[64 - i] = 64 - i;
        }
        codes[32] = "1";
        symbols[32] = 32;
        return new Vlc(9, codes, symbols);
    }

    /**
     * Inverts a position-to-scan-index matrix into a scan-index-to-position table.
     *
     * @param order the scan index of every raster position
     * @return the raster position of every scan index
     */
    private static int[] invert(int[] order) {
        var result = new int[64];
        for (var position = 0; position < 64; position++) {
            result[order[position]] = position;
        }
        return result;
    }
