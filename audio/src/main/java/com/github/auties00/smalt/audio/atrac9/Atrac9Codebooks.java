    /**
     * Builds a codebook from its symbols, packed as {@link Atrac9Codebooks} documents.
     */
    private static Atrac9Codebook book(int valueCount, int valueCountPower, int valueBits, int valueMax,
                                       int maxBitSize, String symbols) {
        var data = Base64.getDecoder().decode(symbols);
        var length = data.length / 3;
        var bits = new byte[length];
        var codes = new int[length];
        for (var i = 0; i < length; i++) {
            bits[i] = data[3 * i];
            codes[i] = (data[3 * i + 1] & 0xFF) << 8 | data[3 * i + 2] & 0xFF;
        }
        return new Atrac9Codebook(bits, codes, valueCount, valueCountPower, valueBits, valueMax, maxBitSize);
    }
