    /**
     * Returns the integer square root of a non-negative 32-bit value, rounded down, by successive
     * approximation ({@code WebRtcSpl_SqrtFloor}).
     *
     * @param value the radicand, non-negative
     * @return the square root, rounded down
     */
    static int sqrtFloor(int value) {
        var root = 0;
        for (var n = 15; n >= 0; n--) {
            var try1 = root + (1 << n);
            if (value >= try1 << n) {
                value -= try1 << n;
                root |= 2 << n;
            }
        }
        return root >> 1;
    }

    /**
     * Fills an array with uniform pseudo-random 15-bit values ({@code WebRtcSpl_RandUArray}).
     *
     * @param vector receives the values
     * @param length the number of values
     * @param seed the generator state, an unsigned 31-bit value
     * @return the updated generator state
     */
    static int randUArray(short[] vector, int length, int seed) {
        for (var i = 0; i < length; i++) {
            seed = (seed * 69069 + 1) & 0x7FFFFFFF;
            vector[i] = (short) (seed >>> 16);
        }
        return seed;
    }
