    /**
     * Builds the table of a packed code.
     *
     * @param packed the codewords, packed as {@code length << 26 | codeword << 10 | symbol}
     * @return the table
     */
    private static VlcTable build(int[] packed) {
        var codes = new int[packed.length];
        var lengths = new int[packed.length];
        var symbols = new int[packed.length];
        for (var i = 0; i < packed.length; i++) {
            lengths[i] = packed[i] >>> 26;
            codes[i] = (packed[i] >>> 10) & 0xFFFF;
            symbols[i] = packed[i] & 0x3FF;
        }
        return new VlcTable(codes, lengths, symbols);
    }

