package com.github.auties00.smalt.video.av1.internal;

/**
 * Defines the film grain synthesis kernels of AV1 (AV1 specification section 7.18.3): generation of
 * the auto-regressive grain templates and application of scaled grain to 32-row stripes of a
 * picture.
 *
 * <p>Grain templates ("grain LUTs") are {@code short[]} arrays of {@link #GRAIN_LUT_SIZE} signed
 * values laid out as {@code (GRAIN_HEIGHT + 1)} rows of {@link #GRAIN_WIDTH} entries; the luma
 * template fills {@link #GRAIN_WIDTH} by {@link #GRAIN_HEIGHT} entries, a chroma template of a
 * horizontally (vertically) subsampled layout fills only the first {@link #SUB_GRAIN_WIDTH}
 * columns ({@link #SUB_GRAIN_HEIGHT} rows). Scaling tables are {@code byte[]} arrays of unsigned
 * 8-bit scaling factors indexed by sample value, {@code bitdepthMax + 1} entries long.
 *
 * <p>Planes are {@code short[]} arrays of unsigned samples from {@code 0} to {@code bitdepthMax},
 * addressed by an offset and a row stride in samples. Layouts use the values of
 * {@link SequenceHeader#LAYOUT_I420}, {@link SequenceHeader#LAYOUT_I422} and
 * {@link SequenceHeader#LAYOUT_I444}.
 *
 * <p>Every kernel is stateless and thread-safe and allocates nothing.
 */
public abstract class FilmGrainDsp {
    /**
     * The implementation used by the decoder.
     */
    public static final FilmGrainDsp INSTANCE = new ScalarFilmGrainDsp();

    /**
     * The width of a grain template.
     */
    public static final int GRAIN_WIDTH = 82;

    /**
     * The height of a grain template.
     */
    public static final int GRAIN_HEIGHT = 73;

    /**
     * The width of the chroma grain template of a horizontally subsampled layout.
     */
    public static final int SUB_GRAIN_WIDTH = 44;

    /**
     * The height of the chroma grain template of a vertically subsampled layout.
     */
    public static final int SUB_GRAIN_HEIGHT = 38;

    /**
     * The size of the luma blocks grain is applied to, and the height of a stripe.
     */
    public static final int FG_BLOCK_SIZE = 32;

    /**
     * The number of entries of a grain template buffer: one padding row more than
     * {@link #GRAIN_HEIGHT}.
     */
    public static final int GRAIN_LUT_SIZE = (GRAIN_HEIGHT + 1) * GRAIN_WIDTH;

    /**
     * Constructs a kernel set.
     */
    protected FilmGrainDsp() {
    }

    /**
     * Generates the luma grain template: Gaussian noise filtered by the luma auto-regressive
     * filter (AV1 specification section 7.18.3.3).
     *
     * @param buf         the template, of at least {@link #GRAIN_LUT_SIZE} entries; the first
     *                    {@link #GRAIN_HEIGHT} rows are written
     * @param data        the film grain parameters
     * @param bitdepthMax the largest sample value: 255, 1023 or 4095
     */
    public abstract void generateGrainY(short[] buf, FilmGrainData data, int bitdepthMax);

    /**
     * Generates a chroma grain template, whose auto-regressive filter includes the contribution of
     * the co-located luma template when luma scaling points exist.
     *
     * @param layout      the pixel layout: {@link SequenceHeader#LAYOUT_I420},
     *                    {@link SequenceHeader#LAYOUT_I422} or {@link SequenceHeader#LAYOUT_I444}
     * @param buf         the chroma template, of at least {@link #GRAIN_LUT_SIZE} entries
     * @param bufY        the luma template generated by {@link #generateGrainY}
     * @param data        the film grain parameters
     * @param uv          the chroma plane: 0 for Cb, 1 for Cr
     * @param bitdepthMax the largest sample value: 255, 1023 or 4095
     */
    public abstract void generateGrainUv(int layout, short[] buf, short[] bufY, FilmGrainData data, int uv,
                                         int bitdepthMax);

    /**
     * Adds grain to one stripe of the luma plane.
     *
     * <p>The stripe is {@code bh} rows of {@code pw} samples starting at the offsets; source and
     * destination may be the same plane. Grain blocks of 32 by 32 samples sample the template at
     * pseudo-random positions derived from the seed and {@code rowNum}, overlapping blocks being
     * blended when {@link FilmGrainData#overlapFlag} is set.
     *
     * @param dst         the destination plane
     * @param dstOff      the index of the stripe's first destination sample
     * @param src         the source plane
     * @param srcOff      the index of the stripe's first source sample
     * @param stride      the row stride of both planes, in samples
     * @param data        the film grain parameters
     * @param pw          the stripe width in samples
     * @param scaling     the luma scaling table, of {@code bitdepthMax + 1} entries
     * @param grainLut    the luma grain template
     * @param bh          the stripe height, from 1 to {@link #FG_BLOCK_SIZE}
     * @param rowNum      the stripe index, counted from the top of the picture
     * @param bitdepthMax the largest sample value: 255, 1023 or 4095
     */
    public abstract void fgy32x32xn(short[] dst, int dstOff, short[] src, int srcOff, int stride,
                                    FilmGrainData data, int pw, byte[] scaling, short[] grainLut, int bh,
                                    int rowNum, int bitdepthMax);

    /**
     * Adds grain to one stripe of a chroma plane.
     *
     * <p>The stripe is {@code bh} chroma rows of {@code pw} samples; source and destination may be
     * the same plane. The scaling index of each sample combines the sample with the co-located
     * (horizontally averaged when subsampled) input luma sample, unless
     * {@link FilmGrainData#chromaScalingFromLuma} is set, in which case the luma sample alone
     * indexes the luma scaling table. When the layout is horizontally subsampled the luma row must
     * hold one readable sample past {@code pw << 1}.
     *
     * @param layout      the pixel layout: {@link SequenceHeader#LAYOUT_I420},
     *                    {@link SequenceHeader#LAYOUT_I422} or {@link SequenceHeader#LAYOUT_I444}
     * @param dst         the destination plane
     * @param dstOff      the index of the stripe's first destination sample
     * @param src         the source plane
     * @param srcOff      the index of the stripe's first source sample
     * @param stride      the row stride of both chroma planes, in samples
     * @param data        the film grain parameters
     * @param pw          the stripe width in chroma samples
     * @param scaling     the scaling table to use, of {@code bitdepthMax + 1} entries
     * @param grainLut    the chroma grain template of the plane
     * @param bh          the stripe height in chroma rows
     * @param rowNum      the stripe index, counted from the top of the picture
     * @param luma        the input (grain-free) luma plane
     * @param lumaOff     the index of the stripe's first luma sample
     * @param lumaStride  the row stride of the luma plane, in samples
     * @param uv          the chroma plane: 0 for Cb, 1 for Cr
     * @param isId        whether the matrix coefficients are the identity matrix, which widens the
     *                    restricted range to 235
     * @param bitdepthMax the largest sample value: 255, 1023 or 4095
     */
    public abstract void fguv32x32xn(int layout, short[] dst, int dstOff, short[] src, int srcOff, int stride,
                                     FilmGrainData data, int pw, byte[] scaling, short[] grainLut, int bh,
                                     int rowNum, short[] luma, int lumaOff, int lumaStride, int uv,
                                     boolean isId, int bitdepthMax);
}
